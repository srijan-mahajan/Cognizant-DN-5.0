public class TypeCasting {
    public static void main(String[] args) {

        double d = 12.89;
        int x = (int)d;

        System.out.println("Double = " + d);
        System.out.println("Int = " + x);

        int num = 10;
        double y = (double)num;

        System.out.println("Converted Double = " + y);
    }
}
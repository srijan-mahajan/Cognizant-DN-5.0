public class DataTypes {
    public static void main(String[] args) {

        int age = 20;
        float salary = 5000.5f;
        double pi = 3.14159;
        char grade = 'A';
        boolean passed = true;

        System.out.println(age);
        System.out.println(salary);
        System.out.println(pi);
        System.out.println(grade);
        System.out.println(passed);
    }
}